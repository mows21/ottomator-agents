class RevenueOptimizer:
    """Optimizes revenue strategies based on performance"""

    def __init__(self):
        self.performance_data: Dict[str, List[float]] = {}

    def record_revenue(self, strategy_name: str, amount: float):
        """Record revenue from a strategy"""
        if strategy_name not in self.performance_data:
            self.performance_data[strategy_name] = []
        self.performance_data[strategy_name].append(amount)

    def get_best_performers(self, top_n: int = 3) -> List[Dict]:
        """Get top performing strategies"""
        performance = [
            {
                "strategy": name,
                "total_revenue": sum(revenues),
                "avg_revenue": sum(revenues) / len(revenues) if revenues else 0
            }
            for name, revenues in self.performance_data.items()
        ]

        return sorted(performance, key=lambda x: x['total_revenue'], reverse=True)[:top_n]

    async def optimize_portfolio(self) -> Dict[str, Any]:
        """Optimize strategy portfolio based on performance"""

        best_performers = self.get_best_performers()

        optimization_prompt = f"""Analyze these revenue strategy performances:

{json.dumps(best_performers, indent=2)}

Recommendations:
1. Which strategies should we scale up (invest more)?
2. Which should we pause or stop?
3. What new strategies should we test?
4. How should we allocate our ${100} daily budget?

Be specific and data-driven."""

        from claude_agent_sdk import query
        recommendations = await query(optimization_prompt)

        return {
            "best_performers": best_performers,
            "recommendations": recommendations
        }


